const CDN = 'https://cdn.jsdelivr.net/gh/yuhonas/free-exercise-db@main/exercises'
const RAW = 'https://raw.githubusercontent.com/yuhonas/free-exercise-db/main/exercises'

/** Se o CDN recusar alguma foto, a mesma imagem vem direto do GitHub. */
export function photoFallback(src: string) {
  return src.startsWith(CDN) ? src.replace(CDN, RAW) : null
}

/** [início, fim] do movimento, ou null se o exercício não tiver foto mapeada. */
export function exercisePhotos(name: string): [string, string] | null {
  const id = PHOTO_IDS[name]
  return id ? [`${CDN}/${id}/0.jpg`, `${CDN}/${id}/1.jpg`] : null
}
